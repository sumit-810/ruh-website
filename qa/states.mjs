/** Screenshots of interactive states (menus, drawers, overlays) for visual review → qa/screens/state-*.png */
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = process.argv[2] || 'http://localhost:8080';
const OUT = new URL('./screens/', import.meta.url).pathname;
const b = await chromium.launch();
const d = await b.newPage({ viewport: { width: 1440, height: 900 } });
await d.goto(`${BASE}/index.html`, { waitUntil: 'networkidle' });
await d.click('[data-mega="0"]'); await d.waitForTimeout(500);
await d.screenshot({ path: `${OUT}state-mega-shop.png` });
await d.keyboard.press('Escape');
await d.click('[data-mega="1"]'); await d.waitForTimeout(500);
await d.screenshot({ path: `${OUT}state-mega-skincare.png` });
await d.keyboard.press('Escape');
await d.click('#featured [data-add]'); await d.waitForTimeout(700);
await d.screenshot({ path: `${OUT}state-bag.png` });
await d.keyboard.press('Escape'); await d.waitForTimeout(600);
await d.click('[data-open-search]'); await d.fill('#search-input', 'body'); await d.waitForTimeout(700);
await d.screenshot({ path: `${OUT}state-search.png` });
await d.keyboard.press('Escape');
await d.goto(`${BASE}/shop.html`, { waitUntil: 'networkidle' });
await d.hover('.pcard'); await d.waitForTimeout(800);
await d.screenshot({ path: `${OUT}state-card-hover.png`, clip: { x: 0, y: 300, width: 1440, height: 700 } });
const m = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await m.goto(`${BASE}/index.html`, { waitUntil: 'networkidle' });
await m.click('[data-open-menu]'); await m.waitForTimeout(700);
await m.click('#mobile-menu .mnav__toggle'); await m.waitForTimeout(200);
await m.screenshot({ path: `${OUT}state-mobile-menu.png` });
await m.goto(`${BASE}/product.html?p=body-mist-no-01`, { waitUntil: 'networkidle' });
await m.screenshot({ path: `${OUT}state-mobile-pdp-top.png` });
await m.evaluate(() => scrollTo(0, 2200)); await m.waitForTimeout(700);
await m.screenshot({ path: `${OUT}state-mobile-sticky.png` });
await m.click('[data-sticky-add]'); await m.waitForTimeout(700);
await m.screenshot({ path: `${OUT}state-mobile-bag.png` });
await b.close();
console.log('state screenshots saved');
