/**
 * Encode the Blender loop frames (tools/render/loops.py) into small, seamless
 * web videos and write the manifest the site reads (assets/js/data/loops.js).
 *
 *   node tools/encode_loops.mjs              # every loop found
 *   node tools/encode_loops.mjs hero_wide    # only these
 *
 * Needs a local ffmpeg with libx264 and libvpx-vp9. No network service is used.
 *
 * The frames are a closed cycle (frame N would equal frame 0), rendered at a
 * low frame rate. The first frame is appended after the last, the sequence is
 * motion-interpolated to 25 fps, and the duplicate is trimmed off, so the
 * video loops without a visible seam.
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'tools/render/out/loops');
const DST = join(ROOT, 'assets/img/loops');
const MANIFEST = join(ROOT, 'assets/js/data/loops.js');
const SECONDS = 10; // loop length
const FPS = 25;
const MAX_BYTES = 1.5 * 1024 * 1024; // per file

const only = process.argv.slice(2);
const names = existsSync(SRC) ? readdirSync(SRC).filter((n) => (!only.length || only.includes(n)) && statSync(join(SRC, n)).isDirectory()) : [];
if (!names.length) {
  console.error('No loop frames found in tools/render/out/loops/ — render them with tools/render/loops.py first.');
  process.exit(1);
}

const manifest = (() => {
  if (!existsSync(MANIFEST)) return {};
  const t = readFileSync(MANIFEST, 'utf8');
  return JSON.parse(t.slice(t.indexOf('{'), t.lastIndexOf('}') + 1) || '{}');
})();

mkdirSync(DST, { recursive: true });
const ff = (args) => execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args], { stdio: 'inherit' });

for (const name of names) {
  const frames = readdirSync(join(SRC, name)).filter((f) => /^\d{4}\.png$/.test(f)).sort();
  if (frames.length < 8) {
    console.warn(`${name}: only ${frames.length} frames, skipped`);
    continue;
  }
  const tmp = mkdtempSync(join(tmpdir(), `loop-${name}-`));
  frames.forEach((f, i) => copyFileSync(join(SRC, name, f), join(tmp, `${String(i).padStart(4, '0')}.png`)));
  copyFileSync(join(SRC, name, frames[0]), join(tmp, `${String(frames.length).padStart(4, '0')}.png`)); // close the cycle
  const inRate = frames.length / SECONDS;
  const total = SECONDS * FPS;
  const vf = `minterpolate=fps=${FPS}:mi_mode=mci:mc_mode=aobmc:me_mode=bidir:vsbmc=1,trim=end_frame=${total},setpts=PTS-STARTPTS,format=yuv420p`;
  const input = ['-framerate', String(inRate), '-i', join(tmp, '%04d.png')];
  const mp4 = join(DST, `${name}.mp4`);
  const webm = join(DST, `${name}.webm`);
  // H.264 — plays everywhere
  ff([...input, '-vf', vf, '-an', '-c:v', 'libx264', '-preset', 'slow', '-crf', '27', '-profile:v', 'high', '-tune', 'film', '-movflags', '+faststart', mp4]);
  // VP9 — usually smaller; kept only when it is
  ff([...input, '-vf', vf, '-an', '-c:v', 'libvpx-vp9', '-b:v', '0', '-crf', '40', '-row-mt', '1', '-deadline', 'good', '-cpu-used', '2', webm]);
  rmSync(tmp, { recursive: true, force: true });

  const size = (p) => (existsSync(p) ? statSync(p).size : Infinity);
  const formats = [];
  if (size(webm) < size(mp4) && size(webm) <= MAX_BYTES) formats.push('webm');
  else rmSync(webm, { force: true });
  if (size(mp4) <= MAX_BYTES) formats.push('mp4');
  else console.warn(`${name}.mp4 is ${(size(mp4) / 1048576).toFixed(2)} MB — over the ${MAX_BYTES / 1048576} MB budget`);
  const dims = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', mp4]).toString().trim().split(',').map(Number);
  manifest[name] = { w: dims[0], h: dims[1], seconds: SECONDS, formats, bytes: Object.fromEntries(formats.map((f) => [f, size(join(DST, `${name}.${f}`))])) };
  console.log(`${name}: ${dims.join('×')} ${formats.map((f) => `${f} ${(manifest[name].bytes[f] / 1024).toFixed(0)} KB`).join(', ')}`);
}

writeFileSync(MANIFEST, `// Generated by tools/encode_loops.mjs — do not edit by hand.\nexport const loops = ${JSON.stringify(manifest, null, 2)};\n`);
